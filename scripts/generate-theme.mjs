/**
 * Generates Material Design 3 color tokens (light + dark) from a single seed color
 * using Google's official HCT / dynamic color algorithm.
 *
 *   pnpm theme:generate            -> uses the default olive seed
 *   pnpm theme:generate "#5d6b2d"  -> custom seed
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
} from '@material/material-color-utilities'

const SEED = process.argv[2] || '#6B7F3A' // olive green
const OUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/app/(frontend)/theme/tokens.css',
)

const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'inverseSurface', 'inverseOnSurface',
  'outline', 'outlineVariant', 'shadow', 'scrim', 'surfaceTint',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
]

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())

const block = (isDark) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0)
  return roles
    .map((r) => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`)
    .join('\n')
}

const light = block(false)
const dark = block(true)

const css = `/* AUTO-GENERATED by scripts/generate-theme.mjs — do not edit by hand.
 * Material Design 3 color scheme (Tonal Spot) from seed ${SEED} (olive green).
 * Theme selection: <html data-theme="light|dark"> overrides, otherwise follows the OS.
 * .md-theme-dark / .md-theme-light force a scheme on a subtree (M3 scoped theming).
 */
:root,
:root[data-theme='light'],
.md-theme-light {
  color-scheme: light;
${light}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${dark.replace(/^/gm, '  ')}
  }
}

:root[data-theme='dark'],
.md-theme-dark {
  color-scheme: dark;
${dark}
}

/* Scoped schemes (e.g. image heroes) also re-establish text color. */
.md-theme-dark,
.md-theme-light {
  color: var(--md-sys-color-on-surface);
}
`

writeFileSync(OUT, css)
console.log(`Wrote ${OUT} from seed ${SEED}`)
